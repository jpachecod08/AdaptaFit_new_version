import re
import unicodedata


def norm(s):
    """Normaliza un nombre: minúsculas, sin acentos, sin paréntesis."""
    s = unicodedata.normalize("NFD", str(s).lower())
    s = "".join(c for c in s if unicodedata.category(c) != "Mn")
    s = re.sub(r"\(.*?\)", " ", s)
    s = re.sub(r"[^a-z0-9]+", " ", s)
    return " ".join(s.split())


_NORM = {norm(k): v for k, v in VIDEOS.items()}


def video_embed_url(nombre):
    """Devuelve la URL embed de YouTube para un ejercicio, o None."""
    if not nombre:
        return None
    clave = norm(nombre)
    if clave in _NORM:
        return _NORM[clave]
    for sim, url in _NORM.items():
        if sim in clave or clave in sim:
            return url
    return None